"""Eval for the agent-readiness rubric. Writes eval/results.md.

What this does and does not show:
  * Calibration: do six hand-built archetype profiles land in the verdict band written down
    BEFORE scoring (the expected band is stored in each profile file)?
  * Robustness: if the category weights were wrong by up to +/-10 points, how often would an
    archetype change band, or two archetypes swap order?
It does NOT validate the rubric against real vendors. That needs labeled public documentation
(see README, "Next step").
"""
import glob
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))
from agent_readiness import load_rubric, score  # noqa: E402

rubric = load_rubric()
profiles = {}
for path in sorted(glob.glob(os.path.join(HERE, "profiles", "*.json"))):
    data = json.load(open(path))
    expect = data.pop("_expect_band")
    profiles[os.path.basename(path)[:-5]] = (expect, data)

rows, hits = [], 0
for name, (expect, answers) in profiles.items():
    r = score(answers, rubric)
    ok = r["band"] == expect
    hits += ok
    rows.append((name, round(r["overall"]), r["band"], expect, ok))

# Robustness: perturb weights, renormalise to sum 100
rng = random.Random(7)
ids = [c["id"] for c in rubric.categories]
base_w = {c["id"]: c["weight"] for c in rubric.categories}
base = {n: score(a, rubric) for n, (_, a) in profiles.items()}
base_order = sorted(base, key=lambda n: base[n]["overall"])
trials, band_changes, order_flips, pair_total = 1000, 0, 0, 0
names = list(profiles)
for _ in range(trials):
    w = {i: max(1.0, base_w[i] + rng.uniform(-10, 10)) for i in ids}
    s = sum(w.values())
    w = {i: 100.0 * v / s for i, v in w.items()}
    res = {n: score(a, rubric, weights=w) for n, (_, a) in profiles.items()}
    band_changes += sum(res[n]["band"] != base[n]["band"] for n in names)
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            a, b = names[i], names[j]
            if base[a]["overall"] != base[b]["overall"]:
                pair_total += 1
                if (base[a]["overall"] < base[b]["overall"]) != (res[a]["overall"] < res[b]["overall"]):
                    order_flips += 1

lines = ["# Eval results: agent-readiness rubric", "",
         "Generated by `eval/run_eval.py` (seeded, deterministic).", "",
         "## 1. Calibration on archetype profiles (expected band written before scoring)", "",
         "| Profile | Score | Band | Expected | Match |", "|---|---|---|---|---|"]
for n, sc, band, ex, ok in rows:
    lines.append("| %s | %d | %s | %s | %s |" % (n, sc, band, ex, "yes" if ok else "**NO**"))
lines += ["", "**Band match: %d of %d.**" % (hits, len(rows)), "",
          "## 2. Robustness to wrong weights (%d trials, each weight +/-10 points)" % trials, "",
          "- Profile band changed in **%.1f%%** of profile-trials (%d of %d)." % (
              100.0 * band_changes / (trials * len(names)), band_changes, trials * len(names)),
          "- Pairwise ranking flipped in **%.1f%%** of pair-trials (%d of %d)." % (
              100.0 * order_flips / pair_total, order_flips, pair_total), "",
          "## What this does not show", "",
          "The archetypes are my own constructions, so section 1 is a calibration check, not validation.",
          "Section 2 says how much the verdicts depend on weights nobody has validated.",
          "Real validation needs published API documentation labeled for a sample of vendors, with a second reviewer.", ""]
open(os.path.join(HERE, "results.md"), "w").write("\n".join(lines))
print("\n".join(lines))
